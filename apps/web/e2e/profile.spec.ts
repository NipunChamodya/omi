test('Google code flow, returning profile, crop/reposition, avatar persistence/removal and logout', async ({
  page,
  context,
}, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Continue with Google' }).click();
  await expect(page.getByRole('button', { name: 'My profile' })).toBeVisible();
  const cookies = await context.cookies();
  expect(
    cookies.find((cookie) => cookie.name === 'omi_session')?.httpOnly,
  ).toBe(true);
  await page.getByRole('button', { name: 'My profile' }).click();
  const dialog = page.getByRole('dialog', { name: 'Your profile' });
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('Display name').fill('නිපුන්');
  await dialog.getByRole('button', { name: 'Save name' }).click();
  await expect(dialog.getByRole('status')).toHaveText('Name saved.');
  // A valid gallery-size PNG generated by the browser keeps this fixture independent of image libraries.
  const image = await page.evaluate(async () => {
    const canvas = document.createElement('canvas');
    canvas.width = 400;
    canvas.height = 300;
    const draw = canvas.getContext('2d')!;
    draw.fillStyle = '#dfc386';
    draw.fillRect(0, 0, 200, 300);
    draw.fillStyle = '#1b6146';
    draw.fillRect(200, 0, 200, 300);
    return canvas.toDataURL('image/png').split(',')[1]!;
  });
  await dialog.getByLabel('Choose profile photo').setInputFiles({
    name: 'gallery.png',
    mimeType: 'image/png',
    buffer: Buffer.from(image, 'base64'),
  });
  await expect(
    dialog.getByRole('img', { name: 'Your selected crop' }),
  ).toBeVisible();
  await dialog.getByLabel('Zoom', { exact: true }).focus();
  await dialog.getByLabel('Zoom', { exact: true }).press('ArrowRight');
  await dialog.getByLabel('Horizontal position').focus();
  await dialog.getByLabel('Horizontal position').press('End');
  await page.screenshot({
    path: testInfo.outputPath('profile-crop-390.png'),
    fullPage: true,
  });
  await dialog.getByRole('button', { name: 'Save photo' }).click();
  await expect(dialog.getByRole('status')).toHaveText('Photo saved.');
  const photo = dialog.locator('.profile-current img');
  await expect(photo).toBeVisible();
  const src = await photo.getAttribute('src');
  expect(src).toContain('/avatars/');
  await dialog.getByRole('button', { name: 'Close profile' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'My profile' }).click();
  await expect(dialog.getByLabel('Display name')).toHaveValue('නිපුන්');
  await expect(dialog.locator('.profile-current img')).toHaveAttribute(
    'src',
    src!,
  );
  const response = await context.request.get(src!);
  expect(response.status()).toBe(200);
  expect(response.headers()['content-type']).toContain('image/webp');
  await dialog.getByRole('button', { name: 'Remove custom photo' }).click();
  await expect(dialog.getByRole('status')).toHaveText('Photo removed.');
  await expect(dialog.locator('.profile-current img')).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByRole('button', { name: 'My profile' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Continue with Google' }).click();
  await page.getByRole('button', { name: 'My profile' }).click();
  await expect(dialog.getByLabel('Display name')).toHaveValue('නිපුන්');
  expect(cookies.some((cookie) => cookie.name === 'mock_subject')).toBe(true);
});
test('profile editor remains reachable on a 320px phone and cancellation keeps the current photo', async ({
  page,
}) => {
  await page.setViewportSize({ width: 320, height: 568 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Continue with Google' }).click();
  await page.getByRole('button', { name: 'My profile' }).click();
  const dialog = page.getByRole('dialog', { name: 'Your profile' });
  await expect(dialog).toBeVisible();
  expect(
    await page.evaluate(
      () => document.documentElement.scrollWidth <= innerWidth,
    ),
  ).toBe(true);
  // Invalid tiny input is a browser-visible error and never sent as a successful avatar.
  await dialog
    .getByLabel('Choose profile photo')
    .setInputFiles({ name: 'small.png', mimeType: 'image/png', buffer: png });
  await dialog.getByRole('button', { name: 'Cancel photo' }).click();
  await expect(
    dialog.getByRole('img', { name: 'Your selected crop' }),
  ).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Close profile' }).click();
  await expect(dialog).toHaveCount(0);
});
test('profile changes reach a live lobby and the same account resumes its seat after sign-out and sign-in', async ({
  page,
  browser,
}) => {
  const guestContext = await browser.newContext({
    baseURL: 'http://127.0.0.1:5173',
    viewport: { width: 390, height: 844 },
  });
  try {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/');
    await page.getByRole('button', { name: 'Continue with Google' }).click();
    await expect(
      page.getByRole('button', { name: 'My profile' }),
    ).toBeVisible();
    await page.getByRole('button', { name: /Create a table/ }).click();
    await expect(
      page.getByRole('heading', { name: 'Your table is ready.' }),
    ).toBeVisible();
    const code = (await page.locator('.invite-box strong').textContent())!;
    const guest = await guestContext.newPage();
    await guest.goto(`/?room=${code}`);
    await guest.getByLabel('Your name').fill('Amila');
    await guest.getByRole('button', { name: /Join table/ }).click();
    await expect(guest.locator('.lobby-seat:not(.empty)')).toHaveCount(2);
    await page.getByRole('button', { name: 'My profile' }).click();
    const dialog = page.getByRole('dialog', { name: 'Your profile' });
    await dialog.getByLabel('Display name').fill('Account friend');
    await dialog.getByRole('button', { name: 'Save name' }).click();
    await expect(dialog.getByRole('status')).toHaveText('Name saved.');
    await expect(guest.locator('.lobby-seat')).toContainText([
      'Account friend',
    ]);
    const image = await page.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = 128;
      canvas.height = 128;
      canvas.getContext('2d')!.fillRect(0, 0, 128, 128);
      return canvas.toDataURL('image/png').split(',')[1]!;
    });
    await dialog.getByLabel('Choose profile photo').setInputFiles({
      name: 'friend.png',
      mimeType: 'image/png',
      buffer: Buffer.from(image, 'base64'),
    });
    await dialog.getByRole('button', { name: 'Save photo' }).click();
    await expect(dialog.getByRole('status')).toHaveText('Photo saved.');
    await expect(guest.locator('.lobby-seat img')).toHaveCount(1);
    await dialog.getByRole('button', { name: 'Sign out' }).click();
    await expect(
      page.getByRole('button', { name: 'Continue with Google' }),
    ).toBeVisible();
    await page.getByRole('button', { name: 'Continue with Google' }).click();
    await expect(
      page.getByRole('heading', { name: 'Your table is ready.' }),
    ).toBeVisible();
    await expect(page.locator('.invite-box strong')).toHaveText(code);
    await expect(page.locator('.lobby-seat:not(.empty)')).toHaveCount(2);
    await expect(page.locator('.lobby-seat')).toContainText(['Account friend']);
  } finally {
    await guestContext.close();
  }
});
